def fill(lang_code, translate):
    path = f"app/translations/{lang_code}/LC_MESSAGES/messages.po"
    po = polib.pofile(path)
    for entry in po:
        if entry.msgid_plural:
            entry.msgstr_plural[0] = translate(entry.msgid)
            entry.msgstr_plural[1] = translate(entry.msgid_plural)
        else:
            entry.msgstr = translate(entry.msgid)
        # `pybabel update` marca "fuzzy" le entry che sembrano un match
        # approssimato di una stringa precedente; una volta che abbiamo
        # fornito la traduzione esplicita nel dict qui sopra non è più una
        # supposizione, quindi il flag va tolto — altrimenti `pybabel compile`
        # la esclude dal .mo per default (stringa non tradotta a runtime).
        if "fuzzy" in entry.flags:
            entry.flags.remove("fuzzy")
    po.save(path)
    print(f"{lang_code}: {len(po)} entries saved.")


def it_translate(msgid):
    if msgid in IT:
        return IT[msgid]
    # Plurali non ancora mappati esplicitamente in IT: mappa a mano sotto.
    PLURALS_IT = {
        "%(num)s day left in your trial": "%(num)s giorno rimasto nel trial",
        "%(num)s days left in your trial": "%(num)s giorni rimasti nel trial",
        "Trial: %(num)s day left": "Trial: %(num)s giorno rimasto",
        "Trial: %(num)s days left": "Trial: %(num)s giorni rimasti",
    }
    if msgid in PLURALS_IT:
        return PLURALS_IT[msgid]
    raise KeyError(f"Missing IT translation for: {msgid!r}")


fill("it", it_translate)
fill("en", lambda msgid: msgid)  # identity: il codice sorgente è già in inglese
